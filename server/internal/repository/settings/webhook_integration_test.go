//go:build integration

// 职责：验证通知协议的持久化、首次初始化和不同公司配置的隔离。
// 输入：config 读取的 PostgreSQL 连接；输出：配置、密钥归属和兜底行为断言。
// 边界：仅使用同一连接的临时 system_settings 表，不修改真实公司或集成配置。
package settings

import (
	"context"
	"database/sql"
	"testing"
	"time"

	_ "github.com/jackc/pgx/v5/stdlib"

	"dandelion/server/internal/config"
)

func TestWebhookCompanyConfiguration(t *testing.T) {
	cfg, err := config.Load()
	if err != nil {
		t.Fatal(err)
	}
	db, err := sql.Open("pgx", cfg.DatabaseURL)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = db.Close() })
	db.SetMaxOpenConns(1)
	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()
	for _, query := range []string{
		`CREATE TEMP TABLE system_settings (
		 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
		 tenant_id UUID, webhook_provider TEXT NOT NULL DEFAULT 'generic',
		 webhook_enabled BOOLEAN NOT NULL DEFAULT false, webhook_url TEXT NOT NULL DEFAULT '',
		 webhook_secret TEXT NOT NULL DEFAULT '', webhook_fields TEXT NOT NULL DEFAULT '["downloadPageUrl"]',
		 api_key TEXT NOT NULL, updated_at TIMESTAMPTZ NOT NULL DEFAULT now())`,
		`CREATE UNIQUE INDEX temp_settings_company ON system_settings(tenant_id) WHERE tenant_id IS NOT NULL`,
		`CREATE UNIQUE INDEX temp_settings_fallback ON system_settings((true)) WHERE tenant_id IS NULL`,
	} {
		if _, err := db.ExecContext(ctx, query); err != nil {
			t.Fatal(err)
		}
	}
	repo := NewRepository(db)
	const companyA = "11111111-1111-4111-8111-111111111111"
	const companyB = "22222222-2222-4222-8222-222222222222"
	const companyC = "33333333-3333-4333-8333-333333333333"
	for _, company := range []string{"", companyA, companyB, companyA} {
		row, err := repo.EnsureRow(ctx, company)
		if err != nil || row.TenantID != company || row.Provider != "generic" || row.APIKey != "" {
			t.Fatalf("首次配置或幂等读取失败：company=%s row=%+v err=%v", company, row, err)
		}
	}
	key, err := repo.RotateAPIKey(ctx, companyA)
	if err != nil {
		t.Fatal(err)
	}
	hook := Webhook{Provider: "feishu", Enabled: true, URL: "https://open.feishu.cn/open-apis/bot/v2/hook/test-only",
		Secret: "test-only", Fields: []string{"appName", "downloadPageUrl"}}
	if err := repo.SaveWebhook(ctx, companyA, hook); err != nil {
		t.Fatal(err)
	}
	row, err := repo.LoadForDelivery(ctx, companyA)
	if err != nil || row.Provider != "feishu" || row.Secret != hook.Secret || row.URL != hook.URL || row.FromFallback {
		t.Fatalf("公司通知配置未正确持久化：%+v err=%v", row, err)
	}
	if owner, err := repo.TenantByAPIKey(ctx, key); err != nil || owner != companyA {
		t.Fatalf("修改通知不能改变 CI 密钥及公司归属：owner=%s err=%v", owner, err)
	}
	if row, err := repo.LoadForDelivery(ctx, companyB); err != nil || row.Provider != "generic" || row.Enabled || row.URL != "" || row.FromFallback {
		t.Fatalf("公司 A 的飞书配置泄漏给公司 B：%+v err=%v", row, err)
	}
	if row, err := repo.LoadForDelivery(ctx, companyC); err != nil || !row.FromFallback || row.TenantID != "" {
		t.Fatalf("未配置公司的通用兜底兼容性被破坏：%+v err=%v", row, err)
	}
}
